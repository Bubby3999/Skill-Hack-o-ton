"""Check every color pair the design uses against WCAG 2.2 AA. Writes CONTRAST.md.

Usage: python3 design/master/contrast.py   (exit code 1 if any pair fails)
Reads hex values from tokens.css, so re-run after any token edit.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
TOKENS = dict(re.findall(r"--((?:color|map)-[\w-]+):\s*(#[0-9A-Fa-f]{6})", (HERE / "tokens.css").read_text()))

MIN = {"text": 4.5, "large": 3.0, "ui": 3.0}

# (foreground, background, kind, where it is used)
PAIRS = [
    # Body text
    ("ink", "paper", "text", "Body text on app background"),
    ("ink", "surface", "text", "Body text on cards, inputs"),
    ("ink", "sunken", "text", "Default tag, view toggle"),
    ("ink", "brand-tint", "text", "Notices, filter tags"),
    ("ink-muted", "paper", "text", "Secondary text on background"),
    ("ink-muted", "surface", "text", "Secondary text on cards, nice-to-have tag"),
    ("ink-muted", "sunken", "text", "Secondary text on wells"),
    ("ink-muted", "brand-tint", "text", "Secondary text in notices"),
    # Brand
    ("brand", "surface", "text", "Links, secondary buttons, action tiles"),
    ("brand", "paper", "text", "Links, back link"),
    ("brand", "brand-tint", "text", "Back link / tile hover, active tab icon"),
    ("on-brand", "brand", "text", "Primary button, user bubble, selected chip"),
    ("on-brand", "brand-strong", "text", "Primary button hover"),
    ("surface", "ink", "text", "Required tag, rank, pins, selected toggle, skip link, Ask panel"),
    ("accent", "ink", "text", "Eyebrow on Ask panel"),
    ("ink", "accent", "text", "Step numbers"),
    ("ink", "accent-tint", "text", "Possible-fit badge"),
    # Status
    ("ok", "ok-tint", "text", "Verified status, strong-fit badge"),
    ("reported", "reported-tint", "text", "Patient-reported status"),
    ("unknown", "unknown-tint", "text", "Unknown status"),
    ("missing", "missing-tint", "text", "Not-available status, poor-fit badge"),
    ("missing", "surface", "text", "Error text, danger button"),
    ("surface", "missing", "text", "Danger button (solid)"),
    ("ink", "missing-tint", "text", "Error notice / error bubble text"),
    # Non-text UI (3:1)
    ("line-strong", "surface", "ui", "Input, chip, radio borders on cards"),
    ("line-strong", "paper", "ui", "Input, chip borders on background"),
    ("brand", "surface", "ui", "Meter: has segment"),
    ("unknown", "surface", "ui", "Meter: unknown stripes; unknown icon"),
    ("missing", "surface", "ui", "Meter: missing outline; missing icon"),
    ("ok", "surface", "ui", "Has / verified icon"),
    ("ink", "paper", "ui", "Focus ring on background"),
    ("ink", "surface", "ui", "Focus ring on cards"),
    ("surface", "ink", "ui", "Focus ring inside Ask panel"),
    ("ink", "map-land", "ui", "Map pin on map"),
    ("reported", "map-land", "ui", "Your-location dot on map"),
]


def luminance(hex_color):
    rgb = [int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def ratio(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def color(name):
    return TOKENS.get(f"color-{name}") or TOKENS[name]


assert round(ratio("#000000", "#FFFFFF"), 1) == 21.0  # self-check

rows, failed = [], 0
for fg, bg, kind, where in PAIRS:
    r = ratio(color(fg), color(bg))
    ok = r >= MIN[kind]
    failed += not ok
    rows.append(f"| `{fg}` {color(fg)} | `{bg}` {color(bg)} | {kind} ≥ {MIN[kind]} | {r:.2f} | {'Pass' if ok else '**FAIL**'} | {where} |")

out = [
    "# Contrast report",
    "",
    "Generated by `contrast.py` from `tokens.css`. Do not edit by hand.",
    "",
    f"**{len(PAIRS) - failed} of {len(PAIRS)} pairs pass WCAG 2.2 AA.** Text: 4.5:1. Non-text UI (borders, icons, meter, focus): 3:1.",
    "",
    "`accent` (marigold) is never used as text or as a control's only boundary, so it has no text pair on light backgrounds.",
    "",
    "| Foreground | Background | Needs | Ratio | Result | Used for |",
    "|---|---|---|---|---|---|",
    *rows,
    "",
]
(HERE / "CONTRAST.md").write_text("\n".join(out))
print(f"{len(PAIRS) - failed}/{len(PAIRS)} pass")
sys.exit(1 if failed else 0)
